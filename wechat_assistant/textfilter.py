# -*- coding: utf-8 -*-
"""文本噪声判据：「这段文字值不值得当**口吻样本**」。

⚠️ 零依赖（不 import 本项目任何东西）—— 因为 `store.py`（从库里取）
和 `ai.py`（从当前屏取）**两条路都要用**，放任何一边都会造成重复或循环。

它**不是**"这段文字是不是垃圾消息"的通用判据（那个做不到，见下），
只回答一个窄问题：**拿它去教模型"我平时怎么说话"，会不会把模型带坏。**

（另有一个**消息级**判据 `is_placeholder()`：只回答"这条是不是微信自己画的
纯占位（图片/动画表情/文件…）"—— 历史里用它过滤，和这里的样本级判据分开。）
"""

#: OCR 把界面/卡片上的字读成正文时最常见的词（2026-10-12 用户实测贴出来的那批）。
#: ⚠️ 白名单式，必然漏 —— 它的作用是**兜住最常见的几个**，不是全覆盖。
UI_WORDS = (
    "小程序", "职位详情", "活动规则", "可领取", "优惠券", "优惠卷",
    "代金", "发送", "返回", "朋友圈", "公众号", "扫一扫", "收付款",
    "微信电脑版", "文件传输助手", "查看详情", "立即领取",
)

#: 微信**自己画的**占位符 —— 这些消息的类型根本不是纯文本，
#: 但它们会以**文字形式**落进消息表（见 `store.py` 里那条
#: “用户快速上翻时 `'动画表情'` 存了 3 份”的实测）。
#: ⚠️ 2026-10-15 用户要求：「聊天记录中如果存在**动画表情**就不要
#:    记录在口吻里面」。
#: ⚠️ 为什么单开一组、不并进 `UI_WORDS`：`UI_WORDS` 是“**界面/卡片上的字**”
#:    （OCR 误读成正文的），而这批是“**消息本身就是那个类型**”，
#:    语义不同，以后要改只改一边。
#: ⚠️ **判据是整串相等，不是包含** —— 否则「这个图片很好看」会跟着被丢。
PLACEHOLDER_EXACT = (
    "图片", "[图片]", "视频", "[视频]", "语音", "[语音]",
    "文件", "[文件]", "链接", "[链接]", "位置", "[位置]",
    "转账", "[转账]", "红包", "[红包]", "名片", "[名片]",
    "音乐", "[音乐]", "聊天记录", "[聊天记录]", "[小程序]",
    "表情", "[表情]", "动画表情", "[动画表情]",
)

#: 汉字占比低于这个数就认为是碎片（`社路79代比10代金势 21元` 这种）。
MIN_HAN_RATIO = 0.4

#: 短于这个长度**不判**（一个字的样本没信息量，但也不该算噪声去报日志）。
MIN_LEN = 1


def han_ratio(s: str) -> float:
    s = s or ""
    if not s:
        return 0.0
    return sum(1 for ch in s if "\u4e00" <= ch <= "\u9fff") / float(len(s))


def is_placeholder(text: str) -> bool:
    """这条消息是不是微信自己画的**纯占位**（图片 / 动画表情 / 文件 / 转账…）。

    ⚠️ 和 `is_noise_text()` **分开**：那个是"口吻样本"的筛子，刻意偏向多丢；
       这里只认"**整条就是一个占位词**"，所以「这个图片很好看」不会被误伤。

    ⚠️ 用途是**消息级**的，两边用法相反（2026-10-17 用户要求）：
       · **历史里**不计入（只是噪声，且历史图片取不到像素）→ 过滤掉；
       · **当前屏**要**保留**并指出来（模型得知道对方发的是一张图/一个表情）。
    """
    return (text or "").strip() in PLACEHOLDER_EXACT


def is_noise_text(text: str) -> bool:
    """这段文字是不是**明显不该当口吻样本**。

    ⚠️ 判据刻意**保守**（宁可放过，也不误杀）：
       误杀一条真样本 = 少一点风格信号（无所谓）；
       放过一条 `KI`   = **AI 开始模仿它**（很糟）。
       所以这里的取舍是**偏向多丢**的 —— 这一点和"消息正文一条都不能丢"**正好相反**，
       别把这个函数拿去过滤正文。
    """
    s = (text or "").strip()
    if not s:
        return True
    # ① 一个汉字都没有
    if han_ratio(s) <= 0.0:
        return True
    # ② 界面/卡片关键词
    for w in UI_WORDS:
        if w in s:
            return True
    # ③ 汉字占比过低（碎片）
    #    ⚠️ 门槛是 **3**（不是 4）—— 实测漏过一个 `21元`（优惠券碎片，3 个字，
    #       汉字占比 1/3）。代价是 `OK啦` 这类也会被丢：**可接受**
    #       （样本少一条无所谓，这函数的取舍本来就更偏向多丢）。
    if len(s) >= 3 and han_ratio(s) < MIN_HAN_RATIO:
        return True
    # ④ 微信自己画的占位符（**整串相等**）—— 它们不是“人说的话”。
    if s in PLACEHOLDER_EXACT:
        return True
    # ⚠️ **不要**写成 `"动画表情" in s`（子串）：实测会把
    #    「这个动画表情好逗」这种**真人说的话**一起丢掉。
    #    上面的 `PLACEHOLDER_EXACT` 已经把 `动画表情` / `[动画表情]` 两种
    #    写法都列进去了，**整串相等就够**。
    return False


def clean_style_samples(texts):
    """把一串候选口吻样本过一遍筛子（保持原顺序、去重）。"""
    out = []
    for t in texts or []:
        s = (t or "").strip()
        if not s or s in out:
            continue
        if is_noise_text(s):
            continue
        out.append(s)
    return out

"""提示词的**文本**都放这里 —— 唯一一份，`ai.py` 和 `settings.py` 都从它取。

为什么要单独一个模块（2026-10-11）

    用户要求「提示词部分要可给用户在设置修改」，选的是**整段可改**：
    「设置 → AI」里有一个多行框，里面就是组装 system prompt 的**模板**，
    可以直接重写，改完保存**立即生效**（保存会重建 `AIClient`，不用重启）。

    于是这段文本要出现在**两个**地方：
      · `ai.py` —— 实际渲染它
      · `settings.py` —— 作为 SPEC 的 `default=`（设置界面的默认值 /
        「恢复默认」按钮的依据）
    写两份必然漂，所以集中到这里。本模块**零依赖**（不 import 本项目的任何东西），
    因此 `settings.py` 引它不会引入 import 环。

⚠️ 用**占位符**表达"每次不同"的部分，别把值硬编进模板：

    {persona}       人设（全局或会话级）
    {relationship}  你们的关系 —— 没设时**整块为空**
    {style}         口吻样本 —— 没有样本时**整块为空**
    {intent}        「我想说」—— 没填时**整块为空**
    {n}             要写几条候选

    上面三个"整块为空"的占位符，展开时**自带结尾的空行**（非空时），
    所以默认模板里把它们直接挨着写就行，不用手工调空行。
"""

#: ⚠️⚠️ **群聊里认不出昵称的成员统一显示成这个**（2026-10-11 用户实测报的）。
#:
#: 为什么不能用「对方」：那词在中文里**暗示"只有两个人"**。群聊里一句 `对方: 好吃`、
#: 隔一句又 `对方: 这个叫做碱水包…` —— 用户以为是一个人，其实是**两个不同的人**
#: （昵称要"同一会话读到 ≥2 次"才认，没认出来的一律走兜底）。模型也会被带偏，
#: 把三个人的发言当成一对一对话来回复。
#:
#: ⚠️ 放在这个模块是因为它**零依赖** —— `ai.py`（渲染提示词）和 `reader.py`
#:    （消息对象）都要用它，而 `ai.py` 不能 import reader（那会把 uiautomation
#:    拖进 AI 模块，测试也会变重）。
#: ⚠️ 一对一里**仍然叫「对方」**（那里是对的）—— 见 `reader.MessageItem.who`。
GROUP_UNKNOWN = "群友"

#: 【硬性要求：不要写成 AI 腔】—— 默认模板里会**原文出现**，
#: 这里留一份常量是为了让老代码/文档有引用点，不是唯一的存放处。
ANTI_TEMPLATE_RULES = """【硬性要求：不要写成 AI 腔】
- 不复述、不总结对方说过的话
- 不解释自己为什么这么回，不加括号补充说明
- 不用「首先 / 其次 / 总之 / 话说回来 / 总的来说」这类连接词
- 不用「亲 / 您 / 加油哦 / 呢」这类客套和讨好
- 不排比、不凑三段式、不写成字数工整的对仗句
- 句尾别习惯性加句号（「？！～…」保留，那是语气）
- 允许不完整的句子、口头语、语气词
- 三条候选不是「温柔版 / 负责版 / 行动版」，而是同一个人在不同心情下随手打的；
  其中一条可以只有两三个字，甚至只是一个语气词"""

#: 【重要：上下文里可能有无关内容】—— 同上，默认模板里原文出现。
FOCUS_RULES = """【重要：上下文里可能有无关内容】
- 「当前消息」是这次要回复的对象。历史里可能有跟它**无关的旧话题**（聊天会跳话题），
  不要去回应那些内容，它们只是背景。
- 判断对方真实意思时，**以与当前消息相关的那部分为准**。
- 如果历史里出现了明显不像聊天消息的东西（一段说明、一段代码、一大段转发的文字），
  忽略它，不要当成对方说的话来回应。"""

#: 关系那块 —— `%s` 是关系名。**结尾带空行**（下一块直接接上就行）。
RELATIONSHIP_BLOCK = "【你们的关系】%s。称呼、语气和分寸都按这个关系来把握。\n\n"

#: 口吻样本那块 —— `%s` 是已经拼好的「- 样本」多行文本。**结尾带空行**。
STYLE_BLOCK = ("【这是「我」平时说话的样子，照着模仿】\n%s\n"
               "（照上面的用词、句子长短、标点习惯写。不要写得比这些更正式、更完整。）"
               "\n\n")

#: 「我想说」那块 —— `%s` 是用户填的那句话。**结尾带空行**。
#:
#: ⚠️ 它压在**前面**（默认模板里放在【输出要求】之前），是**有意**的：
#:    「我」的真实想法只有「我」知道，模型从对话里推不出来；
#:    原来模型只能猜立场，猜错时三条回复一条都用不上。
#:
#: ⚠️⚠️ **这段必须自包含**（2026-10-11）：默认模板换成用户自己写的那份之后，
#:    里面**没有「第一步/第二步」结构** —— 所以这段里**不能**出现
#:    "它压过下面第二步…" 那种指向别处的说法（那会变成**指向不存在的东西**）。
#:    要说明就用「只有「我」知道」这个理由本身。
#:    ⚠️ 判据：`probes/check_prompt_template.py` 里有断言
#:       「渲染结果里不出现『第二步』」。
#:
#: ⚠️ **「同一个立场的不同说法」这层意思现在由用户那份模板承担**
#:    （它写着"同一个人不同心情随手打的"），所以这里不重复。
INTENT_BLOCK = """【最高优先级 ·「我」想表达的意思】
「我」自己说了，这次要表达的是：
「%s」

这是「我」本人的真实想法，比你从对话里能推断出来的任何东西都准。
不要再去猜「我」想要什么，也不许把这个意思换成别的立场。

"""

#: ⚠️⚠️ **第二步的两种写法 —— 默认模板已经不用它们了**（2026-10-11）。
#:
#: 用户给的提示词把"第一步/第二步"整个换成了【硬性禁止】+【上下文规则】，
#: 所以默认模板里**没有 `{step2}`**。保留它们的理由：
#: `render_system` 仍然支持 `{step2}`（谁想写分两步的模板就能用），
#: 删掉会动到 `render_system` 的契约和测试面。
#: ⚠️ **别再往默认模板里加回 `{step2}`** —— 那会把用户那份规则又绕开一层。
STEP2_NORMAL = """【第二步 · 按这个判断写 {n} 条候选】
顺着对方的情绪走，先把情绪接住，再谈事；每条都要能直接发出去。"""

STEP2_INTENT = """【第二步 · 写 {n} 条候选】
严格按上面「我」说的那个意思写。几条是**同一个立场的不同说法**：
换语气（更软 / 更直接 / 更随口）、换长短、换直白程度，让「我」挑顺手的。
不复述对方的话，每条都要是能直接发出去的成品。"""

#: ⚠️⚠️ **默认模板里已经带了输出格式**（2026-10-11 用户给的提示词里自己写了
#: 【输出要求】），所以代码**不再无条件追加**这一段 —— 见 `ai.build_prompts`
#: 里那句「模板里已经有 JSON 结构就不再追加」。留着它是**兜底**：
#: 用户哪天把模板里的输出要求删了，代码会补上，解析就不会坏。
#:
#: 理由（为什么当初要由代码追加）：解析器（`ai.parse_replies`）依赖这个 JSON 结构。
#: 让用户能改它 = 给了一个"改完就静默生成失败"的开关 —— 而"静默失败"是
#: 这个项目里最贵的一类 bug（前面栽过好几次）。
OUTPUT_FORMAT = ('【输出格式】只输出 JSON，不要任何解释、不要加序号：\n'
                 '{"intent": "对方这句话的真实意思（一句话）", '
                 '"replies": ["回复1", "回复2", "回复3"]}')

#: 设置界面上要告诉用户这一框**装的是什么、外面的东西从哪来**。
#:
#: ⚠️⚠️ 2026-10-11 改：这一框**不再**出现占位符（用户要求「框里只放
#:    【硬性禁止】+【上下文规则】」），所以别再写"占位符：…"那种说明 ——
#:    用户照着找一个框里根本没有的记号，只会更困惑。
#:
#: ⚠️ **这段会拼进 SPEC 的 `help`，所以里面不能有 `**` 或反引号** ——
#:    设置界面不会渲染 markdown，它们会原样漏到界面上（有测试卡着这条）。
PLACEHOLDER_HELP = ("只放你自己的规则；人设、关系、口吻、输出格式会自动拼在它前面，"
                    "不用写在这里。清空 = 用回默认。")

#: ⭐ **默认正文 = 用户写的那两段规则，一个占位符、一句输出格式都没有**。
#:
#: ⚠️⚠️ 设置里那个框**只装这一段**（2026-10-11 用户要求「显示并可改
#:    【硬性禁止，必须遵守】【上下文规则】这里的东西就可以」）。
#:    也就是：**框里全是用户自己的话**，看不到 `{persona}` 那种记号，
#:    也看不到【输出要求】。
#:
#:    其余全部由代码在**外面**拼（顺序见 `render_system`）：
#:
#:        PREFIX_TEMPLATE   人设 / 关系 / 口吻样本
#:        INTENT_TEMPLATE   「我想说」（最高优先级）
#:        <这个框>           用户可改的规则
#:        OUTPUT_SPEC       输出格式（**含 `{n}`**，所以条数跟着设置走）
#:
#:    ⚠️ **【输出要求】挪到代码侧是有意的**：它同时是"解析器依赖的输出格式"，
#:       放在框里就等于给用户一个"改完就静默生成失败"的开关。
#:       挪出去之后那个保证**更硬**了 —— 用户根本改不到它。
DEFAULT_SYSTEM_TEMPLATE = """【硬性禁止，必须遵守】
- 只用第一人称，生成可以直接发送的微信消息
- 不复述、不总结对方的话
- 不加括号备注、不解释回复理由
- 禁止使用：首先、其次、总之、话说回来、亲、您、加油哦、呢
- 禁止排比、工整对仗长句
- 不要AI腔，口语碎片化
- 只输出JSON，严禁输出任何思考过程、额外文字、序号
- 输出JSON不要用```代码块包裹，直接裸JSON文本

【上下文规则】
1. 当前消息为本次需要回复内容；历史消息仅作背景，无关旧话题不要回应
2. 若历史内出现代码、说明文本，忽略，不要当成聊天消息
3. 群聊多条不同人连续发言：以最新发言为主，兼顾同批次连续消息
4. 识别对方意图：区分是陈述事情，还是表达情绪。气话不要讲道理、辩解、翻旧账，优先接住情绪
5.上下文可能会有乱码与识别错误的字段，判断后可忽略。
6.消息可能来自群聊，需要分辨发言角色；标记为「我:」的消息是我方历史发言，属于背景，不是对方消息，不要当成待回复内容。"""

#: 拼在**用户正文之前**的那一段：人设 / 关系 / 口吻样本。
#: ⚠️ 这些在设置里各有自己的项（「人设与口吻」分组），所以**不该**再出现在
#:    提示词那个框里 —— 那样等于同一个东西有两处可改，必然漂。
PREFIX_TEMPLATE = """{persona}

{relationship}{style}"""

#: 拼在**用户正文之前**（紧跟 PREFIX）的「我想说」块。
#:
#: ⚠️ 位置：放在用户规则**之前**（不是像以前那样塞在【输出要求】前面）。
#:    理由：那样就得**切开用户的正文**才能插进去 —— 而正文是他整段维护的，
#:    按标记切开很脆（他改一下标题就失效）。放在前面同样醒目，
#:    而且"最高优先级"本来就更该先说。
INTENT_TEMPLATE = "{intent}"

#: 拼在**用户正文之后**的输出格式 —— **代码侧，用户改不到**。
#:
#: ⚠️⚠️ 它同时干两件事：
#:    ① 告诉模型要输出什么结构（解析器 `ai.parse_replies` 依赖它）
#:    ② **条数**：`{n}` 由设置里的「生成几条」填 —— 所以用户正文里
#:       不必出现占位符，条数照样跟着设置走
#:       （之前靠正则去同步正文里写死的"3条候选"，那太脆，已删）。
OUTPUT_SPEC = """【输出要求】
{"intent": "对方这句话的真实意思（一句话）", "replies": ["回复1", "回复2", "回复3"]}
1. intent字段：一句话概括对方真实意图
2. replies：{n}条候选回复，同一个人不同心情随手打的；其中一条可以只有两三个字甚至单语气词"""


def render_system(user_text: str, persona: str = "", relationship: str = "",
                  style_samples=None, user_intent: str = "",
                  n_replies: int = 3) -> str:
    """把**用户正文**（设置里那个框）+ 外面的几块，拼成最终的 system prompt。

    ⚠️⚠️ 参数名是 `user_text`，装的**只是中间那两段规则**
        （【硬性禁止】+【上下文规则】）。人设 / 关系 / 口吻 /「我想说」/
        输出格式由这里在**外面**拼 —— 用户要求「框里只放那两段」。

    拼的顺序：

        {persona}
        {relationship}{style}
        {intent}                 <- 「我想说」，有才拼
        <user_text>              <- **用户可改的那一段**
        OUTPUT_SPEC              <- 输出格式（代码侧，含 {n}）

    ⚠️⚠️ **只用 `str.replace()`，绝不用 `str.format()` / `%`。**
        正文里有 JSON 花括号（`{"intent": ...}`），用户也可能往里粘代码 ——
        `format()` 遇到没转义的 `{` 会直接抛。
        **成品的提示词是数据，不是格式串。**

    ⚠️ 最后把 3 个以上连续换行压成 2 个：某一块为空时不留多余空行。

    ⚠️ `user_text` 为空（用户把框清空了）时**回落到内置默认** ——
        清空不等于"我想要一个空提示词"，那是误操作。

    ⚠️ `{persona}` 为空时填**「你是一个聊天助手。」**，不是空串 ——
        提示词开头连一句"你是谁"都没有时，模型更容易写成通用助手腔。
    """
    import re

    body = (user_text or "").strip() or DEFAULT_SYSTEM_TEMPLATE
    rel = (RELATIONSHIP_BLOCK % relationship) if relationship else ""
    sty = (STYLE_BLOCK % "\n".join("- %s" % s for s in style_samples)) \
        if style_samples else ""
    it = (INTENT_BLOCK % user_intent.strip()) if user_intent else ""
    # ⚠️ 第二步整块换掉（旧机制，默认正文里没有 `{step2}`）。
    #    **先把里面的 `{n}` 填掉** —— 它是在 `{n}` 那一轮之后才插进去的。
    step2 = (STEP2_INTENT if user_intent else STEP2_NORMAL).replace(
        "{n}", str(n_replies))

    # 拼：前缀 + 我想说 + 用户正文 + 输出格式（输出格式在代码侧，用户改不到）
    # ⚠️ 他要是自己在正文里写了 `{intent}`，就按他放的位置来 ——
    #    那时**不要再拼一份**，否则同一段出现两次。
    head = PREFIX_TEMPLATE + ("" if "{intent}" in body else it)
    out = head + body + "\n\n" + OUTPUT_SPEC
    out = out.replace("{step2}", step2)
    out = out.replace("{n}", str(n_replies))
    out = out.replace("{persona}", (persona or "").strip() or "你是一个聊天助手。")
    out = out.replace("{relationship}", rel)
    out = out.replace("{style}", sty)
    out = out.replace("{intent}", it)
    return re.sub(r"\n{3,}", "\n\n", out).strip()
